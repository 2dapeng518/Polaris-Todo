import { deflateSync } from 'node:zlib'
import { writeFileSync } from 'node:fs'

const W = 32
const H = 32
const SAMPLES = 4

const star = [
  [16, 4],
  [19.2, 12.8],
  [28, 16],
  [19.2, 19.2],
  [16, 28],
  [12.8, 19.2],
  [4, 16],
  [12.8, 12.8]
]

function pointInPolygon(x, y, polygon) {
  let inside = false
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [xi, yi] = polygon[i]
    const [xj, yj] = polygon[j]
    const intersects =
      yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi
    if (intersects) inside = !inside
  }
  return inside
}

const rgba = Buffer.alloc(W * H * 4)

for (let py = 0; py < H; py += 1) {
  for (let px = 0; px < W; px += 1) {
    let r = 0
    let g = 0
    let b = 0
    let covered = 0

    for (let sy = 0; sy < SAMPLES; sy += 1) {
      for (let sx = 0; sx < SAMPLES; sx += 1) {
        const x = px + (sx + 0.5) / SAMPLES
        const y = py + (sy + 0.5) / SAMPLES
        const dx = x - 16
        const dy = y - 16
        if (dx * dx + dy * dy > 14.5 * 14.5) continue

        covered += 1
        if (pointInPolygon(x, y, star)) {
          r += 255
          g += 255
          b += 255
        } else {
          r += 15
          g += 118
          b += 110
        }
      }
    }

    if (covered === 0) continue

    const offset = (py * W + px) * 4
    rgba[offset] = Math.round(r / covered)
    rgba[offset + 1] = Math.round(g / covered)
    rgba[offset + 2] = Math.round(b / covered)
    rgba[offset + 3] = Math.round((covered / (SAMPLES * SAMPLES)) * 255)
  }
}

const crcTable = new Uint32Array(256)
for (let n = 0; n < 256; n += 1) {
  let c = n
  for (let k = 0; k < 8; k += 1) {
    c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
  }
  crcTable[n] = c >>> 0
}

function crc32(buffer) {
  let crc = 0xffffffff
  for (const byte of buffer) {
    crc = crcTable[(crc ^ byte) & 0xff] ^ (crc >>> 8)
  }
  return (crc ^ 0xffffffff) >>> 0
}

function chunk(type, data) {
  const typeBuffer = Buffer.from(type)
  const length = Buffer.alloc(4)
  length.writeUInt32BE(data.length)
  const checksum = Buffer.alloc(4)
  checksum.writeUInt32BE(crc32(Buffer.concat([typeBuffer, data])))
  return Buffer.concat([length, typeBuffer, data, checksum])
}

const header = Buffer.alloc(13)
header.writeUInt32BE(W, 0)
header.writeUInt32BE(H, 4)
header[8] = 8
header[9] = 6
header[10] = 0
header[11] = 0
header[12] = 0

const raw = Buffer.alloc((W * 4 + 1) * H)
for (let y = 0; y < H; y += 1) {
  raw[y * (W * 4 + 1)] = 0
  rgba.copy(raw, y * (W * 4 + 1) + 1, y * W * 4, (y + 1) * W * 4)
}

const png = Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  chunk('IHDR', header),
  chunk('IDAT', deflateSync(raw, { level: 9 })),
  chunk('IEND', Buffer.alloc(0))
])

const dataUrl = `data:image/png;base64,${png.toString('base64')}`

writeFileSync(
  'src/main/tray-icon.ts',
  `// Generated by scripts/make-tray-icon.mjs\nexport const TRAY_ICON_DATA_URL =\n  '${dataUrl}'\n`
)

console.log(`tray icon generated: ${png.length} bytes`)